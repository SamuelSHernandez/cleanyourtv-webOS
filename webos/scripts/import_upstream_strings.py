#!/usr/bin/env python3
"""Import the launcher strings this edition shares with the Android launcher, in every locale it has.

    python3 webos/scripts/import_upstream_strings.py <path to a Gathin23/cleanyourtv checkout>

Writes webos/launcher/js/i18n.js. The webOS launcher uses only strings the Android launcher already has, so
every translation comes from upstream's translators (MIT, Copyright (c) 2026 Gathin) and a locale covers
exactly what it covers upstream; a string a locale lacks falls back to English, as Android does. The commit
the strings came from is written into the file's header. Run it again after upstream's translations change;
tests/js/i18n.test.js checks the generated file against the keys the launcher uses.
"""
import json
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET

OUT = Path(__file__).resolve().parents[1] / "launcher" / "js" / "i18n.js"

# The strings the webOS launcher shows. Add a key here only if upstream has it.
KEYS = [
    "inputs", "settings", "live_tv", "no_inputs", "not_available", "cant_open",
    "good_morning", "good_forenoon", "good_afternoon", "good_evening", "good_night", "greeting_with_name",
    "shamsi_month_farvardin", "shamsi_month_ordibehesht", "shamsi_month_khordad", "shamsi_month_tir",
    "shamsi_month_mordad", "shamsi_month_shahrivar", "shamsi_month_mehr", "shamsi_month_aban",
    "shamsi_month_azar", "shamsi_month_dey", "shamsi_month_bahman", "shamsi_month_esfand",
    "dream_name", "launcher_settings", "columns_label", "wallpaper_state", "wallpaper_none",
    "wallpaper_theme_default", "animations_state", "follow_theme", "on", "off", "race_countdown_minutes",
    "tv_settings", "quick_apps", "module_cards", "no_module_cards",
    "tile_move", "reorder", "reorder_hint", "reorder_not_saved", "card_not_saved",
    "app_library", "library_empty", "library_on_home", "library_add_home", "library_remove_shortcut",
    "library_open", "library_hint_add", "library_hint_open",
    "lunar_date_format", "lunar_month_leap", "lunar_year", "lunar_stems", "lunar_branches",
]

# Android resource folder qualifier -> BCP 47 language tag.
SPECIAL = {"b+sr+Latn": "sr-Latn", "in": "id", "iw": "he", "pt-rPT": "pt-PT", "zh-rCN": "zh-CN", "zh-rTW": "zh-TW"}


def tag_for(folder):
    if folder == "values":
        return "en"
    q = folder[len("values-"):]
    return SPECIAL.get(q, q)


def android_text(node):
    text = "".join(node.itertext())
    if len(text) >= 2 and text[0] == text[-1] == '"':
        text = text[1:-1]
    text = re.sub(r"\\(['\"@?])", r"\1", text).replace("\\n", "\n").replace("\\t", "\t")
    # %1$s and %1$d become {1}; %% becomes %.
    text = re.sub(r"%(\d)\$[sd]", r"{\1}", text).replace("%%", "%")
    return text


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    upstream = Path(sys.argv[1]).resolve()
    res = upstream / "launcher" / "app" / "src" / "main" / "res"
    if not (res / "values" / "strings.xml").is_file():
        sys.exit(f"{res}/values/strings.xml not found: pass the root of a Gathin23/cleanyourtv checkout")
    sha = subprocess.run(["git", "-C", str(upstream), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    table = {}
    for folder in sorted({p.parent.name for p in res.glob("values*/strings.xml")}):
        if not (folder == "values" or re.fullmatch(r"values-([a-z]{2,3}(-r[A-Z]{2})?|b\+[A-Za-z+]+)", folder)):
            continue
        found = {}
        for xml in sorted((res / folder).glob("*.xml")):
            root = ET.parse(xml).getroot()
            for n in root.findall("string"):
                if n.get("name") in KEYS:
                    found[n.get("name")] = android_text(n)
            for n in root.findall("string-array"):
                if n.get("name") in KEYS:
                    found[n.get("name")] = [android_text(i) for i in n.findall("item")]
        if found:
            table[tag_for(folder)] = dict(sorted(found.items()))
    missing = [k for k in KEYS if k not in table.get("en", {})]
    if missing:
        sys.exit(f"upstream English has no string for: {', '.join(missing)}")
    body = json.dumps(table, ensure_ascii=False, indent=1, sort_keys=True)
    OUT.write_text(
        "/*\n"
        " * Generated by webos/scripts/import_upstream_strings.py. Do not edit by hand.\n"
        f" * Source: Gathin23/cleanyourtv@{sha or 'unknown'} launcher/app/src/main/res/values(-<locale>)/*.xml\n"
        " * Licence: MIT, Copyright (c) 2026 Gathin; the translations are upstream's translators' work.\n"
        " */\n"
        "(function (root) {\n"
        "  'use strict';\n"
        f"  var STRINGS = {body};\n"
        "  root.CYTV = root.CYTV || {};\n"
        "  root.CYTV.STRINGS = STRINGS;\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = STRINGS;\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(table)} locales, {len(KEYS)} keys) from {sha[:12] or 'an unknown commit'}")


if __name__ == "__main__":
    main()
